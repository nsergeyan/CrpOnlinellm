"""Summarise the full GP runs next to the paper and write results/summary.md.

Run from PyCharm (green button), or: python experiments/summarize_results.py
"""
import csv
import statistics

from crp.paper import GP_MEDIANS, PU_TOTALS
from crp.paths import RESULTS

FULL = {"population": "1000", "generations": "50", "hidden": "max", "training_set": "training"}


def main() -> None:
    with (RESULTS / "gp_full.csv").open(newline="") as f:
        rows = [r for r in csv.DictReader(f) if all(r[k] == v for k, v in FULL.items())]

    lines = [
        "# GP results vs the paper",
        "",
        "Unrestricted scheme, Maximum strategy, terminal set C, population 1,000, 51,000 evaluations.",
        "Total relocations over the 840 Caserta test instances (lower is better). Generated by",
        "`experiments/summarize_results.py` from `results/gp_full.csv`.",
        "",
        "| alpha | runs | our median | paper median | difference | our IQR | our best / worst | PU1 / PU2 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for alpha, paper in GP_MEDIANS.items():
        totals = sorted(int(r["test_total"]) for r in rows if float(r["alpha"]) == alpha)
        if not totals:
            continue
        median = statistics.median(totals)
        q1, _, q3 = statistics.quantiles(totals, n=4)
        lines.append(
            f"| {alpha} | {len(totals)} | {median:,.0f} | {paper:,} | {median - paper:+,.0f} "
            f"| {q1:,.0f} - {q3:,.0f} | {totals[0]:,} / {totals[-1]:,} "
            f"| {PU_TOTALS[1, alpha]:,} / {PU_TOTALS[2, alpha]:,} |"
        )
    lines += [
        "",
        "PU1 / PU2 are the paper's hand-made rules; our Python versions reproduce these totals exactly",
        "(tests/test_pu.py). IQR = interquartile range, the middle 50% of the runs.",
    ]
    text = "\n".join(lines) + "\n"
    (RESULTS / "summary.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
