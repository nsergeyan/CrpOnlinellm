"""Compare the LLM methods (EoH, ReEvo, CALM) with GP and write results/llm_comparison.md.

Run from PyCharm (green button), or: python experiments/compare_methods.py

All methods use the same training and test yards and scorer. EoH, ReEvo, CALM and GP-500 have
500 evaluations; GP-51,000 is the full-budget reference. A run whose best rule fails on the test
set counts as the worst result (README decision 31). Significance: two-sided Mann-Whitney U
test (normal approximation with tie correction); A12 = the chance that a run of the row method
beats a run of the column method (0.5 = equal, above 0.5 = the row method is usually better).
"""
import csv
import itertools
import json
import math
import re
import statistics

from crp.paths import RESULTS

ALPHAS = ("0.5", "0.3", "0.1")
LLM_METHODS = ("calm", "eoh", "reevo")
NAMES = {"calm": "CALM", "eoh": "EoH", "reevo": "ReEvo", "gp500": "GP-500 (pop 50)",
         "gp500_100": "GP-500 (pop 100)", "gp51k": "GP-51,000"}
BUDGET = 500
CHECKPOINTS = (20, 50, 100, 200, 300, 400, 500)


def read_csv(name: str) -> list[dict]:
    with (RESULTS / name).open(newline="") as f:
        return list(csv.DictReader(f))


def total(value: str) -> float:
    """A test total; an empty one (the rule failed on the test set) counts as the worst."""
    return math.inf if value in ("", "None") else float(value)


def mann_whitney_p(a: list[float], b: list[float]) -> float:
    """Two-sided p-value of the Mann-Whitney U test, normal approximation with tie correction."""
    values = sorted((v, group) for group, sample in enumerate((a, b)) for v in sample)
    ranks, ties, i = [0.0] * len(values), 0.0, 0
    while i < len(values):
        j = i
        while j < len(values) and values[j][0] == values[i][0]:
            j += 1
        for k in range(i, j):
            ranks[k] = (i + j + 1) / 2  # average rank of a group of equal values
        ties += (j - i) ** 3 - (j - i)
        i = j
    n1, n2, n = len(a), len(b), len(a) + len(b)
    u = sum(r for r, (_, group) in zip(ranks, values) if group == 0) - n1 * (n1 + 1) / 2
    variance = n1 * n2 / 12 * ((n + 1) - ties / (n * (n - 1)))
    return math.erfc(abs(u - n1 * n2 / 2) / math.sqrt(2 * variance))


def a12(a: list[float], b: list[float]) -> float:
    """Chance that a run of a beats a run of b (fewer relocations), ties counting half."""
    return sum((x < y) + 0.5 * (x == y) for x in a for y in b) / (len(a) * len(b))


def fmt(x: float) -> str:
    return "failed" if math.isinf(x) else f"{x:,.0f}"


def plain_code(code: str) -> str:
    """The code without docstrings, comments and spacing, to find exact repeats."""
    code = re.sub(r'"""[\s\S]*?"""', "", code)
    return re.sub(r"\s+", " ", re.sub(r"#.*", "", code)).strip()


def rule_logs(method: str, alpha: str) -> list[list[dict]]:
    logs = []
    for seed in range(1, 11):
        with (RESULTS / "llm_runs_full" / f"{method}_a{alpha}_s{seed}.jsonl").open() as f:
            logs.append([json.loads(line) for line in f][:BUDGET])
    return logs


def main() -> None:
    llm, gp500, gp51k = read_csv("llm_full.csv"), read_csv("gp_500.csv"), read_csv("gp_full.csv")
    lines = [
        "# LLM methods vs GP",
        "",
        "Total relocations (lower is better). Test totals over the 840 Caserta yards, training totals",
        "over the 840 training yards. EoH, ReEvo and CALM: 10 runs per alpha, Qwen3-14B with thinking",
        "off; GP: 30 runs per alpha. Every method except GP-51,000 has 500 evaluations. Generated by",
        "`experiments/compare_methods.py`; the method and its tests are described in its docstring.",
    ]
    for alpha in ALPHAS:
        runs = {m: [r for r in llm if r["method"] == m and r["alpha"] == alpha] for m in LLM_METHODS}
        tests = {m: [total(r["test_total"]) for r in rows] for m, rows in runs.items()}
        tests["gp500"] = [total(r["test_total"]) for r in gp500 if r["alpha"] == alpha and r["population"] == "50"]
        tests["gp500_100"] = [total(r["test_total"]) for r in gp500 if r["alpha"] == alpha and r["population"] == "100"]
        tests["gp51k"] = [total(r["test_total"]) for r in gp51k if r["alpha"] == alpha]

        lines += ["", f"## alpha {alpha}", "", "**Test totals**", "",
                  "| method | runs | median | IQR | best | worst | failed on test |", "|---|---|---|---|---|---|---|"]
        for m, values in tests.items():
            q1, median, q3 = statistics.quantiles(values, n=4)
            lines.append(f"| {NAMES[m]} | {len(values)} | {fmt(median)} | {fmt(q1)} - {fmt(q3)} "
                         f"| {fmt(min(values))} | {fmt(max(values))} | {sum(map(math.isinf, values))} |")

        lines += ["", "**Pairwise tests on the test totals** (A12 > 0.5: the first method is usually better)", "",
                  "| methods | p (Mann-Whitney) | A12 |", "|---|---|---|"]
        for a, b in itertools.combinations(tests, 2):
            p = mann_whitney_p(tests[a], tests[b])
            lines.append(f"| {NAMES[a]} vs {NAMES[b]} | {p:.4f}{' *' if p < 0.05 else ''} | {a12(tests[a], tests[b]):.2f} |")

        logs = {m: rule_logs(m, alpha) for m in LLM_METHODS}
        lines += ["", "**Median best training total after k evaluations**", "",
                  "| method | " + " | ".join(map(str, CHECKPOINTS)) + " |", "|---" * (len(CHECKPOINTS) + 1) + "|"]
        for m in LLM_METHODS:
            row = [statistics.median(min(r["total"] for r in log[:k] if r["total"] is not None) for log in logs[m])
                   for k in CHECKPOINTS]
            lines.append(f"| {NAMES[m]} | " + " | ".join(f"{v:,.0f}" for v in row) + " |")

        lines += ["", "**Search behaviour** (medians over the runs)", "",
                  "| method | valid rules | repeats an earlier total | repeats exact code | distinct totals "
                  "| test minus training |", "|---|---|---|---|---|---|"]
        for m in LLM_METHODS:
            valid, same_total, same_code, distinct = [], [], [], []
            for log in logs[m]:
                totals = [r["total"] for r in log if r["total"] is not None]
                codes = [plain_code(r["code"]) for r in log]
                valid.append(len(totals) / len(log))
                same_total.append((len(totals) - len(set(totals))) / len(log))
                same_code.append((len(codes) - len(set(codes))) / len(log))
                distinct.append(len(set(totals)))
            gap = [total(r["test_total"]) - float(r["train_fitness"]) for r in runs[m] if r["test_total"] not in ("", "None")]
            lines.append(f"| {NAMES[m]} | {statistics.median(valid):.1%} | {statistics.median(same_total):.1%} "
                         f"| {statistics.median(same_code):.1%} | {statistics.median(distinct):.0f} "
                         f"| {statistics.median(gap):+,.0f} |")
    lines += ["", "\\* p < 0.05. IQR = the middle 50% of the runs. A failed run (its best rule crashed on a test",
              "yard) counts as the worst result in the medians and tests."]
    path = RESULTS / "llm_comparison.md"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
